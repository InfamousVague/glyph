// Makes lib/app/token_sheet.g.dart: the app's token sheet as Dart, so the app's start reads and parses no CSS.
//
//   dart run tool/token_sheet.dart            writes the file
//   dart run tool/token_sheet.dart --check    says whether the file is what it would write, and writes nothing
//
// The token engine reads the very stylesheets the web app ships (the kit's tokens.css, then the app's ink.css,
// app.css and typefaces.css: 110 KB) and keeps the rules that declare custom properties. Read at every launch,
// that was four files loaded and parsed before anything else began: 71 ms of a quiet Mac's 87 before the app ran,
// and on a phone, where a compiled build walks every regular expression in an interpreter, more. The rules do not
// change between a build and the next launch, so they are worked out here, once, and compiled in as constants.
//
// Run it again whenever one of the four stylesheets changes (tool/sync-design.sh brings them from ../glyph).
// test/app/token_sheet_test.dart holds the file to the stylesheets, rule for rule, and fails with this command in
// its words when they have drifted.
import 'dart:io';

import 'package:glacier/token_sheet.dart';

/// The stylesheets, in the order the page loads them: the kit's own (`glacierTokensAsset`), then the app's
/// (lib/app/style_sheets.dart `appStyleSheets`). Named here again because both of those are in libraries that
/// import the engine, which this tool runs without; the test holds the generated sheet to those two.
const sheets = ['packages/glacier/assets/css/tokens.css', 'assets/css/ink.css', 'assets/css/app.css', 'assets/css/typefaces.css'];

const target = 'lib/app/token_sheet.g.dart';

String _text(String value) {
  if (!value.contains("'") && !value.contains(r'$') && !value.contains(r'\') && !value.contains('\n')) return "'$value'";
  return "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";
}

String _condition(TokenCondition c) {
  if (c.isClass) return 'TokenCondition.cls(${_text(c.key)})';
  final value = c.value == null ? 'null' : _text(c.value!);
  return 'TokenCondition.attr(${_text(c.key)}, $value${c.negated ? ', negated: true' : ''})';
}

String generate() {
  final sheet = TokenSheet.parseAll([for (final path in sheets) File(path).readAsStringSync()]);
  // Each condition is said once and named, as most rules ask the same few things (`[data-theme='dark']`).
  final names = <String, String>{};
  String named(TokenCondition c) => names.putIfAbsent(_condition(c), () => '_c${names.length}');
  final rules = StringBuffer();
  for (final rule in sheet.rules) {
    final conditions = [for (final c in rule.conditions) named(c)].join(', ');
    final subject = rule.subject == null ? null : [for (final c in rule.subject!) named(c)].join(', ');
    final declarations = [for (final entry in rule.declarations.entries) '${_text(entry.key)}: ${_text(entry.value)}'].join(', ');
    rules.writeln('  TokenRule(conditions: [$conditions], declarations: {$declarations}, specificity: ${rule.specificity}, order: ${rule.order}'
        '${rule.reducedMotion ? ', reducedMotion: true' : ''}${subject == null ? '' : ', subject: [$subject]'}),');
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/token_sheet.dart from the four stylesheets the token engine reads. Do not edit: run')
    ..writeln('//   dart run tool/token_sheet.dart')
    ..writeln('// after any of them changes (${sheets.join(', ')}).')
    ..writeln('// test/app/token_sheet_test.dart holds this to what parsing them answers, rule for rule.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes')
    ..writeln("import 'package:glacier/glacier.dart';")
    ..writeln()
    ..writeln('/// The app\'s token sheet: `loadTokenSheet(more: appStyleSheets)` worked out as the app was built, ${sheet.rules.length} rules.')
    ..writeln('/// A sheet of its own each time it is asked for, since a sheet is added to (lib/settings/settings_css.dart).')
    ..writeln('TokenSheet appTokenSheet() => TokenSheet.kept(_rules);')
    ..writeln();
  for (final entry in names.entries) {
    out.writeln('const ${entry.value} = ${entry.key};');
  }
  out
    ..writeln()
    ..writeln('const List<TokenRule> _rules = [')
    ..write(rules)
    ..writeln('];');
  return out.toString();
}

void main(List<String> args) {
  final made = generate();
  final file = File(target);
  if (args.contains('--check')) {
    final same = file.existsSync() && file.readAsStringSync() == made;
    stdout.writeln(same ? '$target is what the stylesheets make.' : '$target is not what the stylesheets make: dart run tool/token_sheet.dart');
    exitCode = same ? 0 : 1;
    return;
  }
  file.writeAsStringSync(made);
  stdout.writeln('wrote $target (${made.length} characters)');
}
