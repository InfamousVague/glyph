// ---- zones: every city's zone, its offsets from UTC ---------------------------------------------------------------
//
// Dart has no time-zone database without a package, and the time solver (core/fillFacts.ts `offsetMinutes`) asks
// `Intl` for a zone's offset at a moment. So, for every zone in core/timeZones.ts `CITY_ZONES`, this writes
//
//   lib/ai/support/time_zone_table.dart   the zone's offset at the start of 2000 and every change of it up to the
//                                         start of 2041, to the minute, as `offsetMinutes` itself answers;
//   test/ai/fixtures/zone_offsets.json    {zone: [[minutes since 1970, offset], …]}: the minute before and the
//                                         minute of every change, and 300 other moments spread over the range.
async function zones() {
  const { CITY_ZONES } = await import(`${GLYPH_APP}core/timeZones.ts`);
  const { offsetMinutes } = await import(`${GLYPH_APP}core/fillFacts.ts`);
  const MINUTE = 60_000;
  const from = Date.UTC(2000, 0, 1) / MINUTE;
  const to = Date.UTC(2041, 0, 1) / MINUTE;
  const names = [...new Set(Object.values(CITY_ZONES))].sort();
  const offset = (zone, minute) => offsetMinutes(zone, new Date(minute * MINUTE));
  const table = {};
  const samples = {};
  for (const zone of names) {
    const first = offset(zone, from);
    const changes = [];
    let last = first;
    // A day at a time, then halved down to the minute: no zone changes twice in a day.
    for (let at = from + 1440; at <= to; at += 1440) {
      const now = offset(zone, at);
      if (now === last) continue;
      let low = at - 1440;
      let high = at;
      while (high - low > 1) {
        const mid = Math.floor((low + high) / 2);
        if (offset(zone, mid) === last) low = mid;
        else high = mid;
      }
      changes.push([high, now]);
      last = now;
    }
    table[zone] = { first, changes };
    const points = [];
    for (const [at] of changes) points.push(at - 1, at);
    // A fixed spread: a step that is no whole number of days, so every hour of the day and every season is met.
    const step = Math.floor((to - from) / 300) + 7;
    for (let at = from + 3; at < to; at += step) points.push(at);
    samples[zone] = points.sort((a, b) => a - b).map((at) => [at, offset(zone, at)]);
  }
  const lines = [
    '// GENERATED by tool/ai_fixtures.mjs (section `zones`) from the web app\'s own `offsetMinutes` (core/fillFacts.ts)',
    `// under Node ${process.versions.node}, ICU ${process.versions.icu}, tz ${process.versions.tz}. Do not edit: run the tool again.`,
    '',
    '/// Every zone the time solver knows (ai/support/time_zones.dart `cityZones`), with its offset from UTC in minutes',
    '/// at the start of 2000 and every change of it up to the start of 2041: the first number is the offset at',
    '/// 2000-01-01T00:00Z, and after it come pairs, the minute a change takes hold (counted from 1970-01-01T00:00Z) and',
    '/// the offset from then on.',
    'library;',
    '',
    `/// The first minute the table answers for, counted from 1970: 2000-01-01T00:00Z.`,
    `const int zoneTableFrom = ${from};`,
    '',
    `/// The minute the table stops at: 2041-01-01T00:00Z.`,
    `const int zoneTableTo = ${to};`,
    '',
    'const Map<String, List<int>> zoneTable = {',
  ];
  for (const zone of names) {
    const { first, changes } = table[zone];
    const numbers = [first, ...changes.flat()];
    const rows = [];
    for (let i = 0; i < numbers.length; i += 16) rows.push(`    ${numbers.slice(i, i + 16).join(', ')},`);
    lines.push(`  '${zone}': [`, ...rows, '  ],');
  }
  lines.push('};', '');
  writeFileSync(`${HERE}lib/ai/support/time_zone_table.dart`, lines.join('\n'));
  mkdirSync(`${HERE}test/ai/fixtures`, { recursive: true });
  writeFileSync(`${HERE}test/ai/fixtures/zone_offsets.json`, `${JSON.stringify(samples)}\n`);
}

// ---- unaccent: letters with their accents off ---------------------------------------------------------------------
//
// The page folds words with `text.normalize('NFD').replace(/\p{Diacritic}/gu, '')` (ai/fills/shape.ts `lowerWords`,
// core/timeZones.ts `fold`), and Dart has no normaliser without a package. This writes
// lib/ai/support/unaccent_table.dart: every character whose NFD form differs from itself, with that form once its
// diacritics are off. Hangul syllables are left out (11,172 of them, taken apart by arithmetic in unaccent.dart), and so
// are the diacritics themselves, which the Dart side takes off with the same `\p{Diacritic}`.
async function unaccent() {
  const rows = [];
  for (let cp = 0; cp <= 0x10ffff; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    if (cp >= 0xac00 && cp <= 0xd7a3) continue;
    const ch = String.fromCodePoint(cp);
    const apart = ch.normalize('NFD');
    if (apart === ch) continue;
    const folded = [...apart.replace(/\p{Diacritic}/gu, '')].map((c) => c.codePointAt(0).toString(16).toUpperCase());
    rows.push(`${cp.toString(16).toUpperCase()}=${folded.join(' ')}`);
  }
  const lines = [
    '// GENERATED by tool/ai_fixtures.mjs (section `unaccent`) from JavaScript\'s own `normalize(\'NFD\')` and',
    `// \`\\p{Diacritic}\` under Node ${process.versions.node}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}. Do not edit: run the tool again.`,
    '',
    '/// Every character whose canonical decomposition (NFD) is not itself, Hangul syllables aside: a line each, the',
    '/// character\'s code point in hex, `=`, and the code points of its decomposition with the diacritics taken off',
    '/// (none at all where nothing is left).',
    'library;',
    '',
    "const String unaccentTable = '''",
    ...rows,
    "''';",
    '',
  ];
  writeFileSync(`${HERE}lib/ai/support/unaccent_table.dart`, lines.join('\n'));
  // A few words the Dart test folds, with what the page makes of them.
  const words = ['São Paulo', 'bogotá', 'Zürich', 'cafés', 'ohayō gozaimasu', 'Ελληνικά ά ώ', 'й ё Й', 'が ぱ ヴ', '화장실이 어디예요', 'złoty Łódź', 'é ạ̈', 'ǆ ﬁ Å', 'ṩ ệ ǻ', 'हिंदी क़', '豈 更', 'naïve façade coöperate', '', 'plain words 123'];
  const fold = (text) => text.normalize('NFD').replace(/\p{Diacritic}/gu, '');
  mkdirSync(`${HERE}test/ai/fixtures`, { recursive: true });
  writeFileSync(`${HERE}test/ai/fixtures/unaccent_web.json`, `${JSON.stringify(words.map((text) => ({ text, folded: fold(text), lower: fold(text.toLowerCase()) })), null, 1)}\n`);
}

